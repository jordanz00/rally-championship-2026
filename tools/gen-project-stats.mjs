#!/usr/bin/env node
/**
 * Generate js/ui/project-stats.js from the repo — never invent numbers.
 *
 * Usage: node tools/gen-project-stats.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");

function walk(dir, pred, out = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "node_modules" || e.name === ".git") continue;
      walk(p, pred, out);
    } else if (pred(p, e.name)) out.push(p);
  }
  return out;
}

function lineCount(path) {
  try {
    return readFileSync(path, "utf8").split(/\r?\n/).length;
  } catch {
    return 0;
  }
}

const jsFiles = walk(join(root, "js"), (p) => /\.(js|mjs)$/.test(p));
const toolsMjs = walk(join(root, "tools"), (p) => p.endsWith(".mjs"));
const qaScripts = toolsMjs.filter((p) => /\/qa-[^/]+\.mjs$/.test(p));
const docsMd = walk(join(root, "docs"), (p) => p.endsWith(".md"));
const glb = walk(join(root, "assets"), (p) => p.endsWith(".glb"));
const gfx = walk(join(root, "js/gfx"), (p) => p.endsWith(".js"));
const physics = walk(join(root, "js/physics"), (p) => p.endsWith(".js"));
const audio = walk(join(root, "js/audio"), (p) => p.endsWith(".js"));
const tracks = walk(join(root, "js/tracks"), (p) => /\.(js|mjs)$/.test(p));
const vendor = walk(join(root, "vendor"), (p) => p.endsWith(".js"));

let jsLoc = 0;
for (const f of jsFiles) jsLoc += lineCount(f);

const stats = {
  generatedAt: new Date().toISOString().slice(0, 10),
  stages: 4,
  jsModules: jsFiles.length,
  jsLinesOfCode: jsLoc,
  gfxModules: gfx.length,
  physicsModules: physics.length,
  audioModules: audio.length,
  trackModules: tracks.length,
  qaScripts: qaScripts.length,
  toolsScripts: toolsMjs.length,
  docs: docsMd.length,
  glbAssets: glb.length,
  vendorModules: vendor.length,
  cars: 3,
};

const out = `/**
 * Project statistics — AUTO-GENERATED by tools/gen-project-stats.mjs
 * Do not edit by hand. Do not invent numbers.
 * Regenerated: ${stats.generatedAt}
 */

/** @type {Readonly<typeof PROJECT_STATS>} */
export const PROJECT_STATS = Object.freeze(${JSON.stringify(stats, null, 2)});
`;

writeFileSync(join(root, "js/ui/project-stats.js"), out);
console.log("Wrote js/ui/project-stats.js", stats);
